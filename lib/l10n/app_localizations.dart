  String money(double yer) {
    const yerPerUsd = 530.0, sarPerUsd = 3.75;
    switch (currency) {
      case 'USD':
        return '\$${(yer / yerPerUsd).toStringAsFixed(0)}';
      case 'SAR':
        return '${(yer / yerPerUsd * sarPerUsd).toStringAsFixed(0)} SAR';
      default:
        return '${yer.toStringAsFixed(0)} ${t('yer')}';
    }
  }

  String get currency => AppState.instance?.currency ?? 'YER';

  String duration(int minutes) {
    final h = minutes ~/ 60, m = minutes % 60;
    if (h == 0) return '$m ${t('min')}';
    if (m == 0) return '$h ${t('hour')}';
    return '$h ${t('hour')} $m ${t('min')}';
  }

